// Сбор снимка для трассировки зазоров IMU (ТЗ v0.9A §3).
//
// Платформенная часть: здесь собираются числа, которые модуль
// compat/diag/fc_gap_trace.c хранить умеет, а добывать — нет.
//
// Вызывается ИЗ ЗАДАЧИ РЕАЛЬНОГО ВРЕМЕНИ, поэтому внутри только чтение
// счётчиков из ОЗУ. Ни печати, ни обхода стеков, ни аллокаций: запас стека и
// куча дописываются позже фоновой задачей и помечаются отдельным признаком,
// чтобы никто не принял значение «через секунду после» за значение
// «в момент».
#pragma once

#include <stdint.h>

/** Зазор превысил порог — собрать и сохранить снимок. Дешёвая операция. */
void fc_gap_port_capture(uint64_t now_us, uint64_t prev_us, uint32_t gap_us);

/** Дописать дорогие поля. Вызывается фоновой задачей, не из контура. */
void fc_gap_port_fill_deferred(void);

/** Печать накопленных событий. Только из консоли. */
void fc_gap_port_print(void);
