// Политика здоровья IMU: когда ориентации можно доверять (ТЗ v0.9C §2-§4).
//
// ЧТО ИЗМЕНИЛОСЬ И ПОЧЕМУ. До v0.9C один неудачный обмен по I²C или один
// отвергнутый семпл защёлкивали отказ навсегда. На 1.7 млн чтений сбоев было
// два, за двадцатиминутную развёртку отвергнутых семплов — пять. При такой
// частоте машина не может проработать долго: любой одиночный транзиент
// снимает тягу до вмешательства человека.
//
// Это не было дефектом. Это была осознанная политика той поры, когда выход
// на мотор был недостижим и цена ложного отказа равнялась нулю. С появлением
// реального транспорта цена изменилась, и политику надо менять вместе с ней.
//
// ПРИНЦИП. Право на тягу зависит не от того, «был ли хоть один плохой
// семпл», а от того, «есть ли прямо сейчас достаточно свежая и достоверная
// ориентация». Плохой семпл сам по себе не отнимает ориентацию: предыдущая
// остаётся пригодной, пока не устарела.
//
// ТРИ ИСХОДА, А НЕ ДВА. Прежний бинарный OK/НЕ OK не различал «данные
// временно негодны» и «датчика больше нет». Разница существенная: первое
// восстановимо само, второе требует человека.
#pragma once

#include <stdbool.h>
#include <stdint.h>

typedef enum {
    FC_IMU_PERMIT_OK = 0, // ориентация свежая и достоверная
    FC_IMU_PERMIT_HOLD,   // тяги нельзя, но положение восстановимо без человека
    FC_IMU_PERMIT_LOST,   // защёлка: нужен явный fault-clear и повторное вооружение
} FcImuPermit;

typedef enum {
    FC_IMU_POLICY_STALE = 1u << 0,        // возраст последнего годного семпла
    FC_IMU_POLICY_NO_SAMPLE = 1u << 1,    // годного семпла не было вовсе
    FC_IMU_POLICY_COMM_BURST = 1u << 2,   // серия неудачных обменов
    FC_IMU_POLICY_INVALID_BURST = 1u << 3,// серия непригодных семплов
    FC_IMU_POLICY_ACCEL_LOW_BURST = 1u << 4, // затяжной провал модуля ускорения
    FC_IMU_POLICY_BUS_STUCK = 1u << 5,    // шина не отпускается
    FC_IMU_POLICY_REINIT_FAILED = 1u << 6,// переинициализация не удалась
    FC_IMU_POLICY_REASON_COUNT = 7
} FcImuPolicyReason;

typedef struct {
    // Свежесть, при которой ориентации ещё можно доверять для выхода на
    // мотор. Совпадает с границей свежести команды у координатора
    // (FC_DUAL_COMMAND_FRESH_US) намеренно: разные пороги дали бы окно, в
    // котором тяга разрешена по одной проверке и запрещена по другой.
    uint32_t torque_freshness_us;

    // Возраст, после которого датчик считается потерянным. Вдвое больше
    // предыдущего — между ними лежит восстановимая полоса, которой раньше не
    // существовало вовсе.
    uint32_t latch_age_us;

    // Серии. Выведены из времени, а не назначены: при периоде 2000 мкс
    // 10 семплов подряд это ровно 20 мс, 20 семплов — 40 мс. Держать их
    // отдельными числами значило бы завести вторую временную модель рядом с
    // первой.
    uint32_t hold_samples;
    uint32_t latch_samples;
} FcImuPolicyConfig;

typedef struct {
    uint64_t now_us;
    uint64_t last_valid_us;
    bool have_valid;

    uint32_t consecutive_read_failures; // обмен не удался
    uint32_t consecutive_invalid;       // семпл непригоден (гироскоп, нулевой модуль)
    uint32_t consecutive_accel_low;     // модуль ускорения мал, но семпл годен

    bool bus_stuck;      // шина не отпускается, сброс не помог
    bool reinit_failed;  // переинициализация датчика не удалась
} FcImuPolicyInputs;

/** Период контура, мкс. Отсюда выводятся длины серий. */
#define FC_IMU_POLICY_PERIOD_US 2000u

FcImuPolicyConfig fc_imu_policy_default_config(void);

/**
 * Оценить право на тягу. reason_mask заполняется ВСЕМИ сработавшими
 * причинами, а не первой: чинить по одной, каждый раз заново гадая, что ещё
 * не так, — плохой способ разбираться с отказом датчика.
 */
FcImuPermit fc_imu_policy_evaluate(const FcImuPolicyConfig *cfg, const FcImuPolicyInputs *in,
                                   uint32_t *reason_mask);

const char *fc_imu_permit_name(FcImuPermit p);
const char *fc_imu_policy_reason_name(FcImuPolicyReason r);
