// Контракт будущего разрешения выхода на мотор (ТЗ v0.7C §15, v0.7D §19).
//
// ЭТОТ МОДУЛЬ НИЧЕГО НЕ РАЗРЕШАЕТ. В текущих сборках выхода на мотор не
// существует как кода, и функция ниже нужна не для того, чтобы что-то
// открыть, а чтобы список условий был записан один раз, в одном месте и в
// исполняемом виде — до того, как появится соблазн собрать его наспех рядом с
// первым работающим backend-ом.
//
// Правило, вокруг которого всё построено: условие — ЗАПРЕЩАЮЩЕЕ. Каждый вход
// умеет только не пустить. Ни один вход, вернувшись в норму, не включает
// выход обратно сам — восстановление одного слоя не должно возвращать тягу
// (ТЗ §5). Возврат к движению — отдельное осознанное действие человека, и
// именно поэтому здесь есть отдельный вход operator_armed, который никакая
// автоматика выставить не может.
//
// Порядок барьеров, от ближнего к дальнему (ТЗ §5). Последним право снять
// тягу имеет ESC, и это правильно: он единственный, кто продолжает работать,
// когда FloatCore перестал существовать.
//
//   1. контур управления      — жив ли, идут ли итерации в срок
//   2. IMU                    — есть ли достоверная ориентация
//   3. Supervisor             — состояние машины безопасности
//   4. Motor Gate             — единственная точка выхода
//   5. транспорт CAN          — доходят ли команды
//   6. сторожевой таймер ESC  — timeout_msec, снимает тягу сам
//   7. защиты прошивки ESC    — токи, напряжения, температуры
//
// Слои 1-5 — наши, и все они могут исчезнуть разом при перезагрузке ESP32.
// Именно поэтому слои 6 и 7 обязаны быть настроены до первого подключения
// мотора: они единственные переживают наш отказ.
#pragma once

#include <stdbool.h>
#include <stdint.h>

typedef struct {
    // Слой 1-2: собственный контур и датчик.
    bool boot_phase_done;      // загрузка и её печать завершены (ТЗ §7)
    bool control_loop_healthy; // итерации идут, дедлайны не пропускаются
    bool imu_healthy;
    bool imu_calibrated;
    bool i2c_healthy;

    // Слой 3: машина безопасности.
    bool supervisor_ready;
    bool no_latched_fault;

    // Слой 5: транспорт и узлы.
    bool can_bus_running;
    bool esc_a_healthy;
    bool esc_b_healthy;
    bool command_stream_ok;

    // Качество самой платформы, а не текущего состояния (ТЗ v0.7D §19).
    // Эти четыре входа отвечают не на вопрос «всё ли сейчас в порядке», а на
    // вопрос «доказано ли, что оно вообще может быть в порядке». Их нельзя
    // выставить наблюдением во время работы — только результатом проверки,
    // сделанной заранее.
    bool realtime_qualified;   // длительный прогон пройден, пропусков нет
    bool battery_model_valid;  // fc_battery_model_valid() на реальных числах
    bool watchdog_policy_valid; // fc_command_watchdog_policy_valid()
    bool motor_model_verified; // параметры подтверждены на подключённом моторе

    // Конфигурация, подтверждённая, а не предполагаемая.
    bool motor_config_validated;
    bool battery_config_validated;
    bool app_config_validated;

    // Человек и доска.
    bool operator_armed;   // осознанное действие человека
    bool footpads_engaged; // обе площадки нажаты
} FcMotorPermitInputs;

#define FC_MOTOR_PERMIT_MAX_REASONS 24

typedef struct {
    bool permitted;
    uint32_t reason_count;
    const char *reasons[FC_MOTOR_PERMIT_MAX_REASONS];
} FcMotorPermitResult;

/**
 * Проверить все условия сразу.
 *
 * Возвращает НЕ первое нарушение, а полный список: при разборе отказа знать,
 * что не сошлось одно условие из двадцати, совсем не то же самое, что знать
 * про восемь.
 *
 * Функция чистая: ничего не сохраняет и никуда не обращается.
 */
void fc_motor_permit_evaluate(const FcMotorPermitInputs *in, FcMotorPermitResult *out);

/**
 * Разрешён ли выход на мотор В ЭТОЙ СБОРКЕ.
 *
 * Всегда false, пока нет профиля MOTOR_CAPABLE, и это не проверка во время
 * работы, а свойство сборки: backend-а вывода не существует как кода.
 * Функция нужна, чтобы утверждение можно было проверить тестом, а не только
 * прочитать в комментарии.
 */
bool fc_motor_permit_available_in_this_build(void);

/** Полный перечень условий по именам — для документации и отчётов. */
const char *const *fc_motor_permit_condition_names(uint32_t *n);
