// Отложенная запись во flash (ТЗ v0.9I §11, §12, §13).
//
// ПРОБЛЕМА. Запись во flash отключает кэш инструкций, и на это время встают ОБА
// ядра: измерено 5795 мкс, почти три периода контура. Поэтому писать можно
// только в DISARMED (fc_supervisor_config_write_allowed).
//
// Политика супервизора до v0.9I проверялась лишь при записи в RAM-зеркало. Сам
// КОММИТ задача сброса делала по таймеру, не глядя на состояние. Запрос,
// принятый в DISARMED за мгновение до перехода в READY, уходил во flash уже в
// READY или RUNNING.
//
// РЕШЕНИЕ. Решение принимается в момент коммита, а не записи. Если сейчас
// писать нельзя, запрос не выполняется и НЕ теряется: он остаётся ожидающим и
// выполняется при первом разрешённом состоянии. Отказ переходит в отсрочку.
//
// Модуль не знает ни про flash, ни про супервизор — только про решение. Это
// позволяет проверить поведение на хосте и оставить платформе один вызов.
#pragma once

#include <stdbool.h>
#include <stdint.h>

typedef enum {
    FC_FLASH_IDLE = 0,  // делать нечего
    FC_FLASH_EXECUTE,   // запрос есть, писать можно — выполнить сейчас
    FC_FLASH_DEFER,     // запрос есть, писать нельзя — оставить ожидающим
} FcFlashDecision;

typedef struct {
    bool pending;                 // есть невыполненный запрос
    uint64_t requested;           // сколько раз просили записать
    uint64_t deferred;            // сколько раз запрос пришлось ОТЛОЖИТЬ (эпизоды)
    uint64_t executed;            // сколько записей выполнено
    uint64_t failed;              // сколько выполненных закончились ошибкой
    uint32_t last_duration_us;    // длительность последней операции
    uint32_t max_duration_us;
    uint64_t pending_since_us;    // когда запрос стал ожидающим
    uint64_t last_executed_at_us;
} FcFlashPolicyStats;

void fc_flash_policy_init(void);

/** Отметить, что данные надо сохранить. Повторные просьбы сливаются в одну. */
void fc_flash_policy_request(uint64_t now_us);

/**
 * Решить, выполнять ли запись сейчас.
 *
 * write_allowed — разрешает ли состояние системы запись прямо сейчас. Решает
 * это супервизор; модуль лишь не даёт исполнить запрос мимо его решения.
 */
FcFlashDecision fc_flash_policy_decide(bool write_allowed, uint64_t now_us);

/** Сообщить итог выполненной записи. Успех снимает ожидание, ошибка — нет. */
void fc_flash_policy_report(bool ok, uint32_t duration_us, uint64_t now_us);

FcFlashPolicyStats fc_flash_policy_stats(void);
