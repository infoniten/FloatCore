// Негативный тест компиляции (ТЗ v0.7B §4, §19).
//
// Этот файл ОБЯЗАН НЕ КОМПИЛИРОВАТЬСЯ в диагностическом профиле. Он проверяет
// главное свойство v0.7B: разрешение передавать read-only запросы не открыло
// дорогу командам мотору.
//
// Проверяются три независимых способа добраться до мотора:
//
//   1. попросить моторный запрос через белый список — такого элемента в
//      перечислении нет, и придумать его нельзя;
//   2. позвать обёртку моторной команды по имени из bldc — имя отравлено;
//   3. собрать кадр самому и отдать в передачу — функции, принимающей
//      (идентификатор, байты), не существует ни публично, ни внутри.
//
// Если файл собрался — это провал теста, а не успех.
#include "../../compat/can/fc_can_diag.h"

void floatcore_attempt_motor_request(void) {
    FcCanDiagFrame f;

    // 1. Моторного намерения в перечислении нет.
    fc_can_diag_build(FC_CAN_DIAG_SET_CURRENT, FC_CAN_SELF_ID, 118, &f);

    // 2. Моторные обёртки отравлены.
    fc_can_set_current(118, 5.0f);

    // 3. Обобщённой передачи не существует.
    fc_can_diag_send_raw(0x976, "\x01", 1);
}
