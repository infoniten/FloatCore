// Учёт процессора по окнам исполнения без двойного счёта (ТЗ v0.9I §15, §25).
//
// Задача меряет своё исполнение как окно «от пробуждения до засыпания». Время
// окна настенное: пока оно открыто, задачу могут вытеснить другие, и их работа
// окажется внутри. Чтобы получить собственный процессор, из окна вычитается
// работа других окон того же ядра, ЗАКОНЧИВШИХСЯ внутри него.
//
// Правило, на котором была ошибка v0.9H: в общий накопитель ядра идёт
// СОБСТВЕННОЕ время окна, а не настенное. Настенное уже содержит чужую работу,
// и складывая его, одну и ту же работу считаешь столько раз, сколько окон её
// накрыло. Проявлялось это тем, что «вытеснение» главного потока Refloat
// выходило больше его же настенного времени итерации.
#pragma once

#include <stdbool.h>
#include <stdint.h>

typedef struct {
    uint64_t busy_us;  // суммарное СОБСТВЕННОЕ время закрытых окон ядра
} FcCpuAccount;

typedef struct {
    uint64_t begin_us;
    uint64_t busy_at_begin;
    bool open;
} FcCpuWindow;

typedef struct {
    uint32_t wall_us;     // настенное время окна
    uint32_t preempt_us;  // чужая работа внутри окна
    uint32_t net_us;      // собственный процессор окна
} FcCpuSample;

void fc_cpu_window_begin(const FcCpuAccount *acc, FcCpuWindow *w, uint64_t now_us);

/** Закрыть окно. false — окно не было открыто, и отсчёт не выдан. */
bool fc_cpu_window_end(FcCpuAccount *acc, FcCpuWindow *w, uint64_t now_us, FcCpuSample *out);
