// ЗДЕСЬ ТОЛЬКО ФОРМА, НЕ СОДЕРЖАНИЕ. Файл объявляет, КАК координатор говорит
// с тем, кто умеет передавать, и не содержит ни одного байта сериализации
// VESC. Настоящая реализация поверх TWAI в этом репозитории отсутствует как
// код, а не «выключена флагом».
//
// Почему интерфейс всё же объявлен в LAB_SAFE. Иначе его нельзя было бы
// проверить: тестовая реализация, записывающая вызовы в массив, физически
// неспособна что-либо передать, но позволяет прогнать все отказные сценарии
// до того, как появится настоящая. Отсутствие интерфейса не сделало бы
// прошивку безопаснее — оно сделало бы её непроверенной.
//
// Граница проходит не по объявлению, а по реализации: имена функций
// сериализации моторных команд отравлены в fc_can_diag.h и не могут быть
// упомянуты ни в одной единице трансляции.
#pragma once

#include "fc_dual_motor.h"

#include <stdbool.h>
#include <stdint.h>

typedef struct {
    const char *name;

    /**
     * Передать команду одной половине. Возвращает true, только если кадр
     * действительно ушёл в железо.
     *
     * Половина адресуется номером FC_DUAL_A / FC_DUAL_B, а не CAN-адресом:
     * знание о том, что 118 — это A, принадлежит настройке, а не логике.
     */
    bool (*send_current)(uint8_t half, float amps, void *ctx);

    /** Монотонное время для измерения разбега между двумя передачами. */
    uint64_t (*now_us)(void *ctx);

    void *ctx;
} FcDualTransport;

typedef struct {
    bool sent[FC_DUAL_HALVES];
    bool pair_whole;   // обе половины получили команду
    uint32_t skew_us;  // фактический разбег между передачами
} FcDualSendResult;

/**
 * Исполнить план. Единственная функция, превращающая план в передачу.
 *
 * Порядок фиксирован: сначала A, затем B. Чередование не вводится, потому что
 * оно усложняет разбор отказа (в каком порядке шло на этот раз?), а выигрыша
 * не даёт: атомарности всё равно нет, а разбег симметризуется не порядком, а
 * его малостью относительно таймаута.
 *
 * Если план запрещает передачу, не передаётся НИЧЕГО и результат пустой.
 */
FcDualSendResult fc_dual_motor_execute(const FcDualMotorPlan *plan, const FcDualTransport *t);
