// Описание шины к контроллерам мотора (ТЗ v0.6A §13, v0.7A, v0.9A §2).
//
// Здесь речь о ТРАНСПОРТЕ КОМАНД МОТОРУ. Способностей три, и путать их
// нельзя: слушать шину, посылать read-only запросы и уметь задать мотору ток
// — разные вещи, и каждая включается своим профилем.
//
// До v0.9A третья отсутствовала во всех профилях, и её появление
// объявлялось ошибкой. Теперь она существует в экспериментальном профиле,
// и называть спроектированное состояние ошибкой нельзя: это приучает
// читать слово «ОШИБКА» как фон. Строка говорит ровно то, что есть, —
// вместе с напоминанием, что способность не равна разрешению.
//
// Проверяется таблицей символов в tools/esp32_smoke.sh.

#include "fc_platform.h"

#include "../../../compat/safety/fc_build_profile.h"

const char *fc_can_backend_name(void) {
#if FC_CAN_TX_AVAILABLE
    // Способность есть. Разрешения по умолчанию нет: после загрузки и после
    // любого отказа система обезоружена, и вооружает её только человек.
    return "RX + diag TX + ТРАНСПОРТ МОТОРУ (" FC_CAN_PROFILE_NAME
           "), выход разрешается только вооружением оператора";
#elif FC_CAN_DIAG_TX_AVAILABLE
    // Передача есть, но только read-only запросы из белого списка. Называть
    // это «RX only» было бы неправдой, а «транспорт есть» — опасной
    // неправдой: команду мотору через этот путь собрать нечем.
    return "RX + read-only diag TX (" FC_CAN_PROFILE_NAME "), транспорта команд мотору нет";
#elif FC_CAN_RX_AVAILABLE
    return "RX only (" FC_CAN_PROFILE_NAME "), транспорта команд мотору нет";
#else
    return "unavailable (TWAI не собран, трансивер не подключён)";
#endif
}
