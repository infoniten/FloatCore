// Разделение времени транзакции I²C на провод и накладные расходы (ТЗ v0.9I §2, §9).
//
// Время чтения N байт линейно по N: каждый байт на проводе — 9 тактов SCL.
//
//     T(N) = a + b·N
//
// Наклон b — время одного байта НА ПРОВОДЕ, со всем, что удлиняет такт, в том
// числе с медленными фронтами. Свободный член a — три служебных байта (адрес+W,
// номер регистра, адрес+R), START, повторный START, STOP и накладные расходы
// драйвера.
//
// Зачем отдельный модуль. «Шина медленная» и «драйвер дорогой» дают одно и то же
// суммарное время; различить их можно только по форме зависимости от N. На
// v0.9H я поделил всё время вызова на такты и получил «шина на 187 кГц» — это
// было неверно. Здесь расчёт отделён и проверен тестами на данных с заранее
// известным ответом.
#pragma once

#include <stdbool.h>
#include <stdint.h>

// Служебных тактов на транзакцию: 3 байта по 9 тактов плюс START, повторный
// START и STOP. Оценка, а не точное число: условия START/STOP занимают доли такта.
#define FC_I2C_FIXED_CLOCKS 30.0

// Порог линейности, мкс. Выше него модель не годится: скорее всего, в минимумы
// попало ожидание блокировки шины или вытеснение, и наклон нельзя читать как
// скорость провода.
#define FC_I2C_FIT_MAX_RESIDUAL_US 15.0

typedef struct {
    bool valid;              // хватило ли разных N для подгонки
    bool linear;             // худшее отклонение ниже порога
    double slope_us_per_byte;
    double intercept_us;
    double max_residual_us;
    double wire_hz;          // частота на проводе, из наклона
    double fixed_wire_us;    // провод служебной части
    double overhead_us;      // свободный член за вычетом провода
} FcI2cFit;

/** Наименьшие квадраты по парам (N, T). n — число пар. */
FcI2cFit fc_i2c_fit(const uint8_t *len, const double *t_us, int n);
