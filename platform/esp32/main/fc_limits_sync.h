// Синхронизация пределов тока с реальных половин ESC (ТЗ v0.9E §7, §8).
//
// ИЕРАРХИЯ ИСТОЧНИКОВ, и смешивать её уровни нельзя:
//
//   1. железо и конфигурация ESC          что физически разрешено
//   2. прочитанные и проверенные пределы  что мы об этом знаем
//   3. экспериментальный предел           что мы разрешаем СЕБЕ в опыте
//   4. запрос Refloat                     что просит контур
//
// Уровень 3 не является пределом ESC и не подменяет его: он всегда строже.
// Итоговая величина обязана удовлетворять всем четырём.
#pragma once

#include "../../../compat/can/fc_vesc_mcconf.h"

#include <stdbool.h>
#include <stdint.h>

typedef struct {
    FcMcconfLimits half[2];  // как прочитано у 118 и 100
    FcMcconfLimits common;   // безопасное пересечение
    uint32_t attempts;
    uint32_t successes;
    uint64_t last_sync_us;
    bool applied;  // пересечение отдано в модель пределов и в VESC_IF
} FcLimitsSyncStatus;

/**
 * Прочитать mcconf обеих половин по CAN и применить пересечение.
 *
 * Возвращает false, если хотя бы одна половина не ответила или её раскладка
 * не та. Частичное применение не делается: пределы одной половины ничего не
 * говорят о второй.
 */
bool fc_limits_sync(void);

FcLimitsSyncStatus fc_limits_sync_status(void);
