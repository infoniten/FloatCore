// Модель параметров мотора и степень доверия к ним (ТЗ v0.7C §8-§10).
//
// Зачем это отдельным модулем. Числа вроде «14 полюсов» и «flux 0.1»
// прочитаны из конфигурации ESC и выглядят как факты, но фактами не
// являются: их туда кто-то ввёл или когда-то измерил на неизвестном моторе.
// Разница между «прочитано» и «подтверждено» стоила проекту одной аномалии
// уже дважды — сначала 120 А/градус на заглушках, потом 11.6 А/градус на
// конфигурации, которая тоже может относиться к другому мотору.
//
// Поэтому у каждого параметра здесь есть не только значение, но и
// происхождение, и степень доверия. Модель отвечает на вопрос
// «можно ли на это опираться», а не только «сколько это».
//
// НИ ОДНО значение отсюда не идёт в путь вывода на мотор. Пути вывода не
// существует. Модель нужна, чтобы к моменту, когда он появится, вопрос
// «а этому числу можно верить» был уже задан и записан.
#pragma once

#include <stdbool.h>
#include <stddef.h>

typedef enum {
    // Выдаётся процедурой детекции FOC. До неё значение в конфигурации может
    // относиться к совершенно другому мотору.
    FC_PARAM_MEASURED_BY_DETECTION = 0,
    // Вводится человеком и детекцией не проверяется.
    FC_PARAM_CONFIGURED,
    // Не свойство мотора, а решение о безопасности: предел, который мы сами
    // выбираем и который детекция трогать не должна.
    FC_PARAM_SAFETY_POLICY,
} FcParamKind;

typedef enum {
    // Значение известно, но физически ничем не подтверждено.
    FC_PARAM_UNVERIFIED = 0,
    // Прочитано из ESC при нас, побайтово сверено с независимым путём.
    // Это доверие к КАНАЛУ, а не к самому числу.
    FC_PARAM_READ_FROM_ESC,
    // Подтверждено на физически подключённом моторе.
    FC_PARAM_VERIFIED,
} FcParamTrust;

typedef struct {
    const char *name;
    const char *units;
    float value_a; // половина 118
    float value_b; // половина 100
    FcParamKind kind;
    // Доверие ОТДЕЛЬНО по половинам. До v0.8A хватало одного поля, потому что
    // не подтверждено было ничего. Теперь мотор подключён к половине 118 и её
    // параметры измерены, а половина 100 стоит без мотора — и сваливать это в
    // одно значение значило бы либо занизить первое, либо завысить второе.
    FcParamTrust trust_a; // половина 118, мотор подключён
    FcParamTrust trust_b; // половина 100, мотор не подключён
    bool needed_by_refloat;
    bool safe_before_detection;      // можно ли опираться до детекции
    bool must_refresh_after_detection;
    const char *note;
    // Что именно переводит параметр в FC_PARAM_VERIFIED (ТЗ v0.7D §15).
    // Формулируется как ПРОВЕРЯЕМОЕ действие, а не как «убедиться».
    const char *verify_criterion;
} FcMotorParam;

/** Таблица параметров. Возвращает количество через n. */
const FcMotorParam *fc_motor_model_all(size_t *n);
const FcMotorParam *fc_motor_model_find(const char *name);

/**
 * Готова ли модель, чтобы на неё опирался выход на мотор.
 *
 * Отвечает false, пока хоть один нужный параметр не подтверждён НА ОБЕИХ
 * половинах. Умолчание — «не готова»: модель закрыта, пока не доказано
 * обратное, а не открыта, пока не найдена ошибка.
 *
 * Требование «на обеих» намеренно строгое. Машина двухмоторная, и готовность
 * одной половины не делает её готовой.
 */
bool fc_motor_model_ready_for_output(const char **why);

/** Сколько параметров ещё не подтверждено физически. */
size_t fc_motor_model_unverified_count(void);

const char *fc_param_kind_name(FcParamKind k);
const char *fc_param_trust_name(FcParamTrust t);
