// Аппаратный ритм контура на ядре реального времени (ТЗ v0.9I §20).
//
// ПОЧЕМУ НЕ ТИК FreeRTOS. В многоядерном IDF счётчик тиков увеличивает только
// ядро 0 (port_systick.c), а ядро 1 на собственном тике лишь подбирает
// разбуженные задачи. Таймеры тиков у ядер независимы и сдвинуты по фазе.
// Измерено: сдвиг 765 мкс, и задача, закреплённая за ядром 1 и спящая в
// vTaskDelayUntil, просыпается то по тику ядра 0, то по своему — через 25 мкс
// после тика ядра 1 и через 789 мкс после тика ядра 0. Период 2 мс прыгал между
// 1235 и 2765 мкс, а от чего зависел источник пробуждения, от того зависела и
// доля «опозданий»: от загрузки ядра.
//
// ЧТО ЗДЕСЬ. Таймер общего назначения с прерыванием на ядре 1 будит
// подписанные задачи уведомлением напрямую, без участия ядра 0.
//
// Прерывание размещается на ядре, которое регистрирует обработчик, поэтому
// fc_rt_clock_start обязан вызываться из задачи, закреплённой за ядром 1.
#pragma once

#include <stdbool.h>
#include <stdint.h>

#include "freertos/FreeRTOS.h"
#include "freertos/task.h"

#define FC_RT_CLOCK_SLOT_IMU 0     // задача датчика: источник ритма контура
#define FC_RT_CLOCK_SLOT_REFLOAT 1 // главный поток Refloat
#define FC_RT_CLOCK_SLOTS 2

typedef struct {
    bool running;
    int core;               // ядро, на котором стартовал таймер
    uint32_t period_us;
    uint64_t alarms;        // срабатываний таймера
    uint64_t wait_timeouts; // ожиданий, не дождавшихся ритма
} FcRtClockStats;

/** Запустить таймер. Вызывать из задачи на ядре 1. */
bool fc_rt_clock_start(uint32_t period_us);

/** Подписать задачу на ритм. NULL — отписать. */
void fc_rt_clock_subscribe(int slot, TaskHandle_t task);

bool fc_rt_clock_running(void);
uint32_t fc_rt_clock_period_us(void);

/**
 * Дождаться следующего срабатывания. Уведомление забирается целиком: если
 * итерация затянулась и срабатываний было два, следующая начнётся сразу, но
 * догонять лишние не будет — так же, как vTaskDelayUntil после пропуска.
 * false — ритм не пришёл за timeout_ms.
 */
bool fc_rt_clock_wait(uint32_t timeout_ms);

FcRtClockStats fc_rt_clock_stats(void);
