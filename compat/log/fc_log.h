// Ограниченный по времени журнал (ТЗ v0.7C §6).
//
// Задача. Печать в UART на 115200 бод блокирует вызывающую задачу на
// миллисекунды: 120 символов — это около 10 мс. Контур баланса живёт с
// периодом 2000 мкс, поэтому один такой вызов из realtime-пути гарантированно
// съедает несколько дедлайнов подряд. На v0.7A это было замечено как «редкий
// пропуск», и списывать его на CAN было бы неверно — виноват UART.
//
// Что здесь есть. Кольцо записей фиксированного размера. Производитель
// форматирует строку прямо в слот и уходит: ни ожидания, ни выделения памяти,
// ни обращения к устройству. Отдельная низкоприоритетная задача забирает
// записи и печатает их вне realtime-путей.
//
// Чего здесь намеренно нет.
//
//   * Блокировки при переполнении. Если потребитель не успевает, новая запись
//     ОТБРАСЫВАЕТСЯ и считается. Ждать в контуре баланса ради строчки лога —
//     ровно та беда, от которой этот модуль избавляет.
//   * Динамической памяти. Размер кольца известен на этапе компиляции.
//   * Молчаливой потери. `dropped` — часть отчёта, а не внутренняя мелочь:
//     если записи теряются, это видно.
//
// Стоимость на стороне производителя — один `vsnprintf` в буфер известного
// размера плюс копия. Это десятки микросекунд против миллисекунд у UART, и
// это ограничено сверху: длина слота фиксирована.
//
// Модуль платформенно-нейтрален и проверяется host-тестами. Взаимное
// исключение производителей — забота платформы: она оборачивает push и pop в
// свою критическую секцию (см. platform/esp32/main/fc_log_port.c).
#pragma once

#include <stdarg.h>
#include <stdbool.h>
#include <stdint.h>

// 48 записей примерно по 170 байт — около 8 КБ. Хватает, чтобы пережить всплеск в
// полтора десятка строк (переинициализация IMU печатает до 14) с запасом, и
// при этом не занимать памяти больше, чем стоит одна строка UART-вывода.
#define FC_LOG_SLOTS 48
#define FC_LOG_MSG_MAX 144
#define FC_LOG_TAG_MAX 12

typedef enum {
    FC_LOG_ERROR = 0,
    FC_LOG_WARN,
    FC_LOG_INFO,
} FcLogLevel;

typedef struct {
    uint64_t t_us;
    uint32_t seq;
    uint8_t level;
    char tag[FC_LOG_TAG_MAX];
    char msg[FC_LOG_MSG_MAX];
} FcLogEntry;

typedef struct {
    FcLogEntry slot[FC_LOG_SLOTS];
    uint32_t head; // куда писать
    uint32_t tail; // откуда читать
    uint32_t count;
    uint32_t seq;

    uint32_t emitted;    // принято записей
    uint32_t dropped;    // отброшено из-за переполнения
    uint32_t truncated;  // сообщение не влезло в слот целиком
    uint32_t high_water; // наибольшая заполненность кольца
} FcLog;

void fc_log_init(FcLog *l);

/**
 * Положить запись. Никогда не блокирует и всегда возвращается быстро.
 *
 * @return false, если кольцо полно и запись отброшена.
 */
bool fc_log_push(FcLog *l, FcLogLevel level, const char *tag, uint64_t t_us, const char *fmt,
                 va_list ap);

/** Забрать самую старую запись. false, если кольцо пусто. */
bool fc_log_pop(FcLog *l, FcLogEntry *out);

uint32_t fc_log_pending(const FcLog *l);
const char *fc_log_level_name(FcLogLevel level);
