// Единый снимок данных IMU (ТЗ v0.6D §5).
//
// Одна физическая выборка датчика → один снимок. Все потребители итерации
// видят ОДИН И ТОТ ЖЕ снимок: Refloat, AHRS, супервизор, телеметрия. Читать
// датчик отдельно для каждого из них запрещено — иначе они получат данные из
// разных моментов времени, а по расхождению между ними невозможно будет
// отличить ошибку монтажа от рассинхронизации.
//
// Снимок неизменяем: публикуется целиком и заменяется целиком.
#pragma once

#include "../safety/fc_imu_health.h"

#include <stdbool.h>
#include <stdint.h>

// Единицы зафиксированы здесь и нигде больше не переопределяются.
//
//   accel_g       — g (ускорение свободного падения). Того же вида, что
//                   ожидает balance_filter.c:86 (сравнивает |acc| с 1.0).
//   gyro_rad_s    — рад/с. Это то, что уходит в callback Refloat:
//                   balance_filter.c:115-124 интегрирует кватернион как
//                   q += 0.5*q*ω*dt, что верно только для рад/с.
//   gyro_dps      — °/с. Это то, что отдаёт imu_get_gyro(); обоснование —
//                   docs/imu_contract.md, раздел о двух разных единицах.
//   углы          — радианы. imu.c:36-40 оборачивает их в rad2deg().
typedef struct {
    uint64_t timestamp_us;    // момент завершения транзакции, монотонный
    uint32_t sample_counter;  // счётчик ПРИНЯТЫХ семплов, без дубликатов
    float dt_s;               // интервал от предыдущего принятого семпла

    // Калиброванные значения: к ним применены поворот и смещения. Именно они
    // уходят в AHRS и в Refloat.
    float accel_g[3];
    float gyro_rad_s[3];
    float gyro_dps[3];
    // Сырые значения, как их отдал датчик. Нужны диагностике и процедуре
    // Detect: калибровку вычисляют ИЗ сырых данных, а не из исправленных.
    // Переименовывать одно в другое запрещено (ТЗ v0.6E §14).
    float accel_raw_g[3];
    float gyro_raw_dps[3];
    float temperature_c;

    // Ориентация, посчитанная платформенным AHRS из ЭТОГО ЖЕ семпла.
    float quat[4];
    float roll_rad;
    float pitch_rad;
    float yaw_rad;

    bool valid;                 // прошёл ли семпл проверку
    FcImuHealthState health;    // состояние диагностики на момент снимка
} FcImuSample;
