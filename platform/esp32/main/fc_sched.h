// Качество пробуждения потоков Refloat (ТЗ v0.7D §11).
//
// Зачем отдельный модуль. Существующая статистика `fc_timing` меряет две
// вещи: период между итерациями и wall-время самой итерации. Ни то, ни
// другое не отвечает на вопрос «а сон-то был точным» — а именно он и
// определяет, крутится ли контур Refloat на заявленных 500 Гц.
//
// Refloat просит сон не «2000 мкс», а «2000 минус то, что я уже потратил»
// (main.c:1058-1059). Значит если механизм пробуждения систематически
// опаздывает, поток будет работать медленнее номинала, а виноватым по
// статистике окажется время исполнения — которое тут ни при чём.
//
// Разделение это не педантизм: лечение у двух причин разное. Долгое
// исполнение лечится кодом, долгое пробуждение — механизмом сна.
#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#define FC_SCHED_MAX_THREADS 4

typedef struct {
    uint64_t iterations;
    uint64_t requested_sum_us;
    uint64_t actual_sum_us;
    uint32_t latency_min_us;
    uint32_t latency_max_us;
    uint64_t latency_sum_us;
    // Грубая гистограмма задержки пробуждения: 0-99, 100-199, …, 900+ мкс.
    uint32_t latency_hist[10];
} FcSchedStats;

void fc_sched_reset(void);
FcSchedStats fc_sched_stats(size_t idx);
